/* vendor-manifold.mjs — rebuild vendor/manifold.js from the manifold-3d package.
 *
 * Manifold ships as an ES module that fetches manifold.wasm next to itself.
 * Neither works from a double-clicked index.html: browsers refuse module
 * scripts and fetch() on file:// URLs. So this writes:
 *   vendor/manifold.js        the loader as a classic script
 *   vendor/manifold.wasm      the engine, fetched and compiled as it streams
 *                             when the app is served over http(s)
 *   vendor/manifold-wasm.js   the same engine as base64, loaded only from
 *                             file://, where fetch() is not allowed
 * WB.loadManifold (engine.js) picks between the last two.
 *
 *   npm install            # pulls manifold-3d as a dev dependency
 *   npm run vendor
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
// The package's "exports" map hides package.json, so locate it on disk.
const pkgDir = join(here, '..', 'node_modules', 'manifold-3d');
const version = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8')).version;

let js = readFileSync(join(pkgDir, 'manifold.js'), 'utf8');
const wasm = readFileSync(join(pkgDir, 'manifold.wasm'));

const exportCount = (js.match(/export default Module;/g) || []).length;
if (exportCount !== 1) throw new Error('Unexpected manifold.js layout: export default found ' + exportCount + ' times');

js = js.replace('export default Module;', 'globalThis.ManifoldModule = Module;');
// `import.meta` is a syntax error outside a module. The browser path only uses
// it to locate the wasm, which we supply directly, so any URL will do.
js = js.split('import.meta.url').join('__manifoldScriptURL');

const head = '/* Manifold ' + version + ' (Apache-2.0, see LICENSE-manifold.txt), repackaged as a classic\n' +
  ' * script. Generated by tools/vendor-manifold.mjs — do not edit by hand. */\n';
const out = head +
  'var __manifoldScriptURL = (typeof document !== "undefined" && document.currentScript && document.currentScript.src) || "file:///manifold.js";\n' +
  js + '\n';
const vendor = join(here, '..', 'vendor');
writeFileSync(join(vendor, 'manifold.js'), out);
writeFileSync(join(vendor, 'manifold.wasm'), wasm);
writeFileSync(join(vendor, 'manifold-wasm.js'), head + 'globalThis.ManifoldWasmBase64 = "' + wasm.toString('base64') + '";\n');
console.log('vendor/: manifold-3d ' + version + ', loader ' + (out.length / 1024).toFixed(0) + ' KB, wasm ' + (wasm.length / 1024).toFixed(0) + ' KB');
